/**
 * 模块职责：概览页的环形进度各自取什么值、写什么字
 * 依赖方向：只依赖 types；不认识注册表，也不认识栅格
 * 生命周期：模块级常量
 * 注意事项：**本表现为空**，原有的 CPU 与内存两枚环已撤，理由见 `GAUGES` 的注释。
 *          形状留着供日后新增取自内核既有接口的环。
 *
 *          新增一枚环时，取值**只可来自 `GET /api/overview`**（本模块的参数就是它）。
 *          从别处再取一份同样的事实，同一个数就有了两个采样时刻，页面上会出现
 *          「这张卡片与那枚环不是一个数」。
 */
import type { Overview } from "../types.js"

/** 一个环形进度 */
export interface GaugeDef {
  /** 组件标识，全站唯一 */
  id: string
  /** 组件名，同时是环下方的标题 */
  title: string
  /**
   * 取比例
   * @param data 概览快照
   * @returns 落在 0-1 内的比例；算不出时 undefined
   */
  ratio: (data: Overview) => number | undefined
  /**
   * 环下方的一行小字
   * @param data 概览快照
   * @returns 小字文本
   */
  hint: (data: Overview) => string
}

/**
 * 环，顺序即页面上的先后
 *
 * **两枚都已撤掉，本表现为空。** 它们量的是本进程占用，而 hardware 面板插件包的双色环
 * 在同一枚环上给出「整机」与「本进程」两段，且直接叫「CPU」「内存」—— 两者并存就是同一页
 * 上两个都在说 CPU 占用，没有任何文案能说清哪个是哪个。不装 hardware 时概览页没有这两枚环。
 *
 * **表留空而不删本文件**：`GaugeDef` 仍是「概览页要一枚环」的唯一表达方式，且空表把
 * 「这里曾有两枚环、为何没有了」留在了代码里 —— 删掉之后，下一个人看到 hardware 提供
 * CPU 环会以为那本就是插件的职责，而不知道它取代了什么。
 *
 * 本进程的那两个数并未从页面上消失：「常驻内存」计数块仍在（`stats.ts`），
 * 且双色环内圈那一段正是本进程 —— 撤掉的是重复的呈现，不是数据。
 */
export const GAUGES: readonly GaugeDef[] = []
